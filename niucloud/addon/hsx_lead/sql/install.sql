-- HSX Lead 1.1.0. Only this plugin owns these tables.
-- The framework substitutes {{prefix}} during installation.
-- No existing table is changed and no historical business record is rewritten.

CREATE TABLE IF NOT EXISTS `{{prefix}}hsx_lead_merchant` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `site_id` int unsigned NOT NULL,
  `name` varchar(120) NOT NULL DEFAULT '',
  `contact_name` varchar(60) NOT NULL DEFAULT '',
  `mobile` varchar(32) NOT NULL DEFAULT '',
  `province_id` int unsigned NOT NULL DEFAULT 0,
  `city_id` int unsigned NOT NULL DEFAULT 0,
  `district_id` int unsigned NOT NULL DEFAULT 0,
  `address` varchar(500) NOT NULL DEFAULT '',
  `service_areas_json` longtext NULL COMMENT 'Explicit service areas; not inferred from the street address',
  `member_id` int unsigned NOT NULL DEFAULT 0 COMMENT 'Existing site member; uses member-token authentication',
  `status` tinyint unsigned NOT NULL DEFAULT 1,
  `remark` varchar(2000) NOT NULL DEFAULT '',
  `create_time` int unsigned NOT NULL DEFAULT 0,
  `update_time` int unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_site_status` (`site_id`,`status`,`id`),
  KEY `idx_site_member` (`site_id`,`member_id`),
  KEY `idx_site_area` (`site_id`,`province_id`,`city_id`,`district_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Lead merchant directory';

CREATE TABLE IF NOT EXISTS `{{prefix}}hsx_lead_connection` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `site_id` int unsigned NOT NULL,
  `merchant_id` bigint unsigned NOT NULL,
  `name` varchar(120) NOT NULL DEFAULT '',
  `provider` varchar(60) NOT NULL DEFAULT '',
  `expected_tenant_id` varchar(100) NOT NULL DEFAULT '',
  `store_id` varchar(100) NOT NULL DEFAULT '',
  `credentials_cipher` longtext NULL COMMENT 'Authenticated encrypted credentials; never returned by API',
  `config_version` int unsigned NOT NULL DEFAULT 1,
  `sync_interval_minutes` int unsigned NOT NULL DEFAULT 60,
  `enabled` tinyint unsigned NOT NULL DEFAULT 0,
  `next_sync_at` int unsigned NOT NULL DEFAULT 0,
  `last_sync_at` int unsigned NOT NULL DEFAULT 0,
  `last_sync_status` varchar(24) NOT NULL DEFAULT 'idle',
  `last_sync_message` varchar(1000) NOT NULL DEFAULT '',
  `active_run_id` bigint unsigned NOT NULL DEFAULT 0,
  `published_run_id` bigint unsigned NOT NULL DEFAULT 0 COMMENT 'Only this completed generation is visible',
  `lease_token` varchar(64) NOT NULL DEFAULT '',
  `lease_until` int unsigned NOT NULL DEFAULT 0,
  `create_time` int unsigned NOT NULL DEFAULT 0,
  `update_time` int unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_site_merchant` (`site_id`,`merchant_id`),
  KEY `idx_site_merchant` (`site_id`,`merchant_id`,`id`),
  KEY `idx_due` (`enabled`,`next_sync_at`,`lease_until`,`id`),
  KEY `idx_site_due` (`site_id`,`enabled`,`next_sync_at`),
  KEY `idx_site_published` (`site_id`,`id`,`published_run_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Merchant read-only ERP connections';

CREATE TABLE IF NOT EXISTS `{{prefix}}hsx_lead_inventory` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `site_id` int unsigned NOT NULL,
  `merchant_id` bigint unsigned NOT NULL,
  `connection_id` bigint unsigned NOT NULL,
  `sync_run_id` bigint unsigned NOT NULL,
  `source_key` varchar(160) NOT NULL,
  `source_id` varchar(100) NOT NULL DEFAULT '',
  `source_store_id` varchar(100) NOT NULL DEFAULT '',
  `tenant_id` varchar(100) NOT NULL DEFAULT '',
  `brand` varchar(100) NOT NULL DEFAULT '',
  `model` varchar(200) NOT NULL DEFAULT '',
  `memory` varchar(100) NOT NULL DEFAULT '',
  `color` varchar(100) NOT NULL DEFAULT '',
  `grade` varchar(100) NOT NULL DEFAULT '',
  `price` decimal(14,2) DEFAULT NULL,
  `trade_price` decimal(14,2) DEFAULT NULL,
  `quantity` decimal(14,3) DEFAULT NULL COMMENT 'NULL means source did not provide quantity',
  `saleable_quantity` decimal(14,3) DEFAULT NULL COMMENT 'Not inferred from quantity',
  `imei` varchar(100) NOT NULL DEFAULT '',
  `cover` varchar(1000) NOT NULL DEFAULT '',
  `images_json` longtext NULL,
  `source_status_json` longtext NULL COMMENT 'Safe source status fields only',
  `snapshot_json` longtext NULL COMMENT 'Whitelist-only source snapshot; excludes credentials',
  `availability` varchar(24) NOT NULL DEFAULT 'unknown' COMMENT 'unknown/available/unavailable; never inferred by default',
  `fetched_at` int unsigned NOT NULL DEFAULT 0,
  `create_time` int unsigned NOT NULL DEFAULT 0,
  `update_time` int unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_generation_source` (`site_id`,`connection_id`,`sync_run_id`,`source_key`),
  KEY `idx_site_merchant_generation` (`site_id`,`merchant_id`,`connection_id`,`sync_run_id`),
  KEY `idx_site_model` (`site_id`,`model`(80),`availability`),
  KEY `idx_site_generation` (`site_id`,`sync_run_id`,`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Generation-based safe ERP inventory snapshots';

CREATE TABLE IF NOT EXISTS `{{prefix}}hsx_lead_sync_run` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `site_id` int unsigned NOT NULL,
  `merchant_id` bigint unsigned NOT NULL,
  `connection_id` bigint unsigned NOT NULL,
  `config_version` int unsigned NOT NULL,
