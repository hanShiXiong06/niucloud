import request from '@/utils/request'

export const getConfig = () => request.get('boyuan/config')
export const saveConfig = (data: any) => request.post('boyuan/config', data)
export const capturePurchaseSource = (id: number) => request.post(`boyuan/purchase-source/${id}`, {intent:'open_review'})
export const preparePurchaseOriginal = (id:number, scope:Record<string,unknown>) => request.post(`boyuan/purchase-source/${id}`, {...scope,intent:'prepare_original'})
export const getPurchase = (id: number) => request.get(`boyuan/purchases/${id}`)
export const savePurchaseDraft = (id: number, data: any) => request.post(`boyuan/purchases/${id}/draft`, data)
export const submitPurchase = (id: number, data: any) => request.post(`boyuan/purchases/${id}/submit`, data)
export const verifyPurchase = (id: number, data: any) => request.post(`boyuan/purchases/${id}/verify`, data)
export const checkPurchaseInventory = (id: number, data: any) => request.post(`boyuan/purchases/${id}/inventory-check`, data)
export const getReferences = (data: any) => request.post('boyuan/reference-search', data)
export const getPurchasePaymentCandidates = (id: number, params: any) => request.get(`boyuan/purchases/${id}/payment-candidates`, { params })
export const capturePurchasePayment = (id: number, data: any) => request.post(`boyuan/purchases/${id}/payment-capture`, data)
export const getPaymentTask = (id: number) => request.get(`boyuan/payment-tasks/${id}`)
export const savePaymentDraft = (id: number, data: any) => request.post(`boyuan/payment-tasks/${id}/draft`, data)
export const submitPaymentTask = (id: number, data: any) => request.post(`boyuan/payment-tasks/${id}/submit`, data)
